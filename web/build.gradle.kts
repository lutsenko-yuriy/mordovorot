// GH-111: `version` in the root build.gradle.kts, as a Kotlin constant the footer and analytics read.
val generateBuildInfo = tasks.register("generateBuildInfo") {
    val version = rootProject.version.toString()
    val outputDir = layout.buildDirectory.dir("generated/buildInfo/kotlin")
    inputs.property("version", version)
    outputs.dir(outputDir)
    doLast {
        val file = outputDir.get().file("web/BuildInfo.kt").asFile
        file.parentFile.mkdirs()
        file.writeText(
            "package web\n\n// Generated by :web:generateBuildInfo from the root build.gradle.kts.\n" +
                "internal object BuildInfo {\n    const val VERSION = \"$version\"\n}\n",
        )
    }
}

// GH-218: Mordie's Web Worker script, built by :web:worker, ships next to web.js as a resource.
// :web:worker:shipToWeb writes it here; the worker project does the writing because `serve` moves
// each project's build directory (GH-124), and :web is configured first, so its path is final.
val workerResources = layout.buildDirectory.dir("generated/worker/resources")

// GH-110: the browser client. DOM-free code goes in commonMain, so its tests run on the JVM and
// Node.js; the page itself is in jsMain.
kotlin {
    jvmToolchain(17)
    jvm {
        testRuns["test"].executionTask.configure { useJUnitPlatform() }
    }
    js {
        browser {
            // Saves live in localStorage, which is per origin, so a moving port would hide them.
            // open = false: the server never opens a tab in the default browser by itself.
            commonWebpackConfig { devServer = devServer?.copy(port = 8080, open = false) }
            // No headless browser in CI: the common tests run on Node.js instead.
            testTask { enabled = false }
        }
        nodejs { testTask { useMocha { timeout = "30s" } } }
        binaries.executable()
    }

    sourceSets {
        commonMain {
            kotlin.srcDir(generateBuildInfo)
            dependencies {
                implementation(project(":shared:viewmodel"))
            }
        }
        jsMain { resources.srcDir(workerResources) }
        commonTest {
            dependencies {
                implementation(kotlin("test"))
                implementation(project(":shared:testing"))
                implementation(libs.kotlinx.coroutines.test)
            }
        }
    }
}

