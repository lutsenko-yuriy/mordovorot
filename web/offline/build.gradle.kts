import org.jetbrains.kotlin.gradle.targets.js.webpack.KotlinWebpack
import java.security.MessageDigest

plugins {
    kotlin("multiplatform")
}

// GH-262: the offline worker, a service worker that keeps the whole game in a cache. It depends on
// nothing but the standard library, so the file holds none of the game and web.js's main() can't
// start inside it. Its file name is fixed for good: an installed worker only re-checks its own URL.
kotlin {
    jvmToolchain(17)
    jvm {
        testRuns["test"].executionTask.configure { useJUnitPlatform() }
    }
    js {
        browser {
            commonWebpackConfig { outputFileName = "offline-worker.js" }
            testTask { enabled = false }
        }
        nodejs { testTask { useMocha { timeout = "30s" } } }
        binaries.executable()
    }

    sourceSets {
        jsMain { kotlin.srcDir(layout.buildDirectory.dir("generated/offlineManifest/kotlin")) }
        commonTest {
            dependencies {
                implementation(kotlin("test"))
            }
        }
    }
}

// The files the worker caches, with their hashes. They are the distribution's own inputs, :web's
// bundle and processed resources, so the list comes from the build and not from a hand-kept list.
// Left out: source maps (large, and only a debugger asks for them), dotfiles (the harness's
// .commit) and the worker itself. The hashes go into the script, so its bytes change exactly when
// a shipped file does, and the browser notices a new version by comparing them (ADR-0006).
val generateOfflineManifest = tasks.register("generateOfflineManifest") {
    val web = project(":web")
    val bundle = web.tasks.named<KotlinWebpack>("jsBrowserProductionWebpack").flatMap { it.outputDirectory }
    val resources = web.tasks.named("jsProcessResources")
    val version = rootProject.version.toString()
    val outputDir = layout.buildDirectory.dir("generated/offlineManifest")
    inputs.files(bundle, resources)
    inputs.property("version", version)
    outputs.dir(outputDir)
    doLast {
        fun sha256(file: File) = MessageDigest.getInstance("SHA-256").digest(file.readBytes()).joinToString("") { "%02x".format(it) }
        val roots = listOf(bundle.get().asFile) + resources.get().outputs.files.files
        val hashes = roots.flatMap { root ->
            root.walkTopDown().filter { it.isFile }.map { it.relativeTo(root).invariantSeparatorsPath to it }.toList()
        }.filter { (path, _) -> !path.endsWith(".map") && !path.startsWith(".") && "/." !in path && path != "offline-worker.js" }
            .associate { (path, file) -> path to sha256(file) }
            .toSortedMap()
        val contentHash = MessageDigest.getInstance("SHA-256")
            .digest(hashes.entries.joinToString("\n") { "${it.key}\u0000${it.value}" }.toByteArray())
            .joinToString("") { "%02x".format(it) }.take(12)
        val cache = "mordovorot-$version-$contentHash"

        val dir = outputDir.get().asFile
        val kotlinFile = File(dir, "kotlin/offline/OfflineManifest.kt")
        kotlinFile.parentFile.mkdirs()
        kotlinFile.writeText(
            "package offline\n\n// Generated by :web:offline:generateOfflineManifest.\n" +
                "internal object OfflineManifest {\n    const val CACHE = \"$cache\"\n\n" +
                "    val FILES: Map<String, String> = mapOf(\n" +
                hashes.entries.joinToString("") { "        \"${it.key}\" to \"${it.value}\",\n" } +
                "    )\n}\n",
        )
        // For :web:checkOfflineManifest, which compares it with the finished distribution.
        File(dir, "manifest.tsv").writeText("cache\t$cache\n" + hashes.entries.joinToString("") { "${it.key}\t${it.value}\n" })
    }
}

// Copies the bundle into :web's distribution (see jsBrowserDistribution there).
tasks.register<Sync>("shipToWeb") {
    from(tasks.named<KotlinWebpack>("jsBrowserProductionWebpack").flatMap { it.outputDirectory }) { include("offline-worker.js") }
    into(project(":web").layout.buildDirectory.dir("generated/offline/dist"))
}

// The generated source is a srcDir, so everything that compiles the worker waits for it.
tasks.matching { it.name == "compileKotlinJs" }.configureEach { dependsOn(generateOfflineManifest) }
